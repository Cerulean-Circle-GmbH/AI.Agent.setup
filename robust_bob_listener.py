#!/usr/bin/env python3
"""
Robust Bob's Message Notification System
Monitors for messages from Alice and creates notification files for Bob to process in chat
"""

import requests
import time
import json
import sys
import os
from datetime import datetime

# Configuration
GATEWAY_URL = "http://localhost:8000"
BOB_ENDPOINT = "http://localhost:8002"
ALICE_NAME = "Alice"
BOB_NAME = "Bob"

# Paths for chat visibility and health
RUN_DIR = "run"
FEED_PATH = os.path.join(RUN_DIR, "bob_chat_feed.md")
HEARTBEAT_PATH = os.path.join(RUN_DIR, "bob_listener_heartbeat.txt")

# Track processed messages to avoid duplicates
processed_messages = set()
last_message_time = time.time()

def ensure_run_dir():
    try:
        os.makedirs(RUN_DIR, exist_ok=True)
    except Exception:
        pass

def log_message(message):
    """Log message with timestamp"""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    print(f"[{timestamp}] {message}")

def append_chat_feed(message_id: str, task_type: str, message_content: str, received_ts: str, status: str):
    """Append an entry to the chat feed file for visibility in Bob's chat."""
    ensure_run_dir()
    header_exists = not os.path.exists(FEED_PATH)
    try:
        with open(FEED_PATH, "a") as feed:
            if header_exists:
                feed.write("# Bob Chat Feed\n\n")
                feed.write("This feed mirrors notifications created by the background listener so Bob can see them in chat.\n\n")
            feed.write(f"## Notification {received_ts}\n")
            feed.write(f"- **Message ID**: `{message_id}`\n")
            feed.write(f"- **Task Type**: `{task_type or 'n/a'}`\n")
            feed.write(f"- **Status**: {status}\n\n")
            feed.write("### Content\n")
            feed.write(f"{message_content}\n\n")
            feed.write("---\n\n")
    except Exception as e:
        log_message(f"❌ Error appending chat feed: {e}")

def write_heartbeat():
    """Update a simple heartbeat file indicating the listener is active."""
    ensure_run_dir()
    try:
        with open(HEARTBEAT_PATH, "w") as hb:
            hb.write(datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    except Exception as e:
        log_message(f"❌ Error writing heartbeat: {e}")

def create_notification_file(message_content, task_type, message_id):
    """Create a notification file for Bob to read in chat"""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    notification_content = f"""# MESSAGE FROM ALICE - {timestamp}

## Message ID: {message_id}
## Task Type: {task_type}
## Received: {timestamp}

## Message Content:
{message_content}

## Instructions for Bob:
1. Read this message carefully
2. Work on the task in the chat interface
3. Send your response back to Alice through the background process
4. Delete this notification file when complete

## Response Instructions:
- Use the send_message function to respond to Alice
- Format your response appropriately for the task type
- Document any learnings or issues encountered

---
*Generated by Bob's notification system*
"""
    
    filename = f"bob_notification_{message_id}.md"
    try:
        with open(filename, 'w') as f:
            f.write(notification_content)
        log_message(f"📝 Created notification file: {filename}")
        # Also append to chat feed for visibility
        append_chat_feed(message_id, task_type, message_content, timestamp, status="created")
        return filename
    except Exception as e:
        log_message(f"❌ Error creating notification file {filename}: {e}")
        return None

def send_message(content, max_retries: int = 3, backoff_seconds: float = 1.0):
    """Send message to Alice with retry via Bob's API only (no gateway fallback)."""
    message = {
        "sender": BOB_NAME,
        "receiver": ALICE_NAME,
        "content": content,
    }

    # Only path: send via Bob's /send endpoint
    last_error_text = None
    for attempt_index in range(1, max_retries + 1):
        try:
            response = requests.post(f"{BOB_ENDPOINT}/send", json=message, timeout=10)
            if response.status_code == 200:
                log_message(f"✅ Sent to Alice (via Bob /send): {content[:50]}...")
                return True
            last_error_text = response.text
            log_message(
                f"⚠️ Attempt {attempt_index}/{max_retries} failed via /send: {last_error_text}"
            )
        except Exception as send_exception:
            last_error_text = str(send_exception)
            log_message(
                f"⚠️ Attempt {attempt_index}/{max_retries} error via /send: {last_error_text}"
            )

        time.sleep(backoff_seconds)

    # If Bob's API is unavailable, do not send. Avoid spoofing through gateway.
    log_message("❌ Could not send via Bob /send after retries; giving up (no gateway fallback)")
    return False

def get_messages():
    """Get messages for Bob from Gateway"""
    try:
        response = requests.get(f"{GATEWAY_URL}/messages?receiver={BOB_NAME}", timeout=10)
        if response.status_code == 200:
            return response.json().get("messages", [])
        else:
            log_message(f"❌ Failed to get messages: {response.text}")
            return []
    except Exception as e:
        log_message(f"❌ Error getting messages: {e}")
        return []

def process_message(message):
    """Process a single message from Alice - create notification for Bob to work in chat"""
    global last_message_time
    
    # Handle Gateway message structure: {receiver, message, task_type}
    content = message.get('message', '')
    task_type = message.get('task_type', '')
    receiver = message.get('receiver', '')
    
    # Create message ID from content and task_type
    message_id = f"{receiver}_{content[:20]}_{task_type}".replace(" ", "_").replace("/", "_")
    
    if message_id in processed_messages:
        return False  # Already processed
    
    processed_messages.add(message_id)
    last_message_time = time.time()
    
    log_message(f"📨 Received from Alice: {content[:100]}...")
    
    # Create notification file for Bob to work in chat
    notification_file = create_notification_file(content, task_type, message_id)
    
    if notification_file:
        log_message(f"✅ Notification created for Bob to process in chat: {notification_file}")
        # Send immediate acknowledgment to Alice
        ack_message = f"📝 Message received and notification created. Bob will process this in chat and respond shortly."
        send_message(ack_message)
    else:
        log_message(f"❌ Failed to create notification file for message: {message_id}")
        # Send error notification to Alice
        error_message = f"⚠️ Error creating notification file. Bob may not see this message immediately."
        send_message(error_message)
    
    return True

def check_health():
    """Check if services are healthy"""
    try:
        gateway_health = requests.get(f"{GATEWAY_URL}/health", timeout=5)
        bob_health = requests.get(f"{BOB_ENDPOINT}/health", timeout=5)
        return gateway_health.status_code == 200 and bob_health.status_code == 200
    except:
        return False

def main():
    """Main listening loop with unlimited restarts"""
    log_message("🚀 Starting Bob's Message Notification System")
    log_message("📋 This system creates notification files for Bob to process messages in chat")
    
    restart_count = 0
    while True:  # Outer infinite loop - never stop
        try:
            log_message(f"🔄 Starting listening cycle (restart #{restart_count})")
            
            # Check health before starting
            if not check_health():
                log_message("⚠️ Health check failed, waiting for services to recover...")
                time.sleep(10)
                continue
            
            # Main listening loop
            while True:  # Inner loop for message processing
                try:
                    # Heartbeat update
                    write_heartbeat()

                    messages = get_messages()
                    
                    if messages:
                        for message in messages:
                            process_message(message)
                    
                    # Sleep between checks
                    time.sleep(2)
                    
                except Exception as inner_error:
                    log_message(f"⚠️ Inner loop error: {inner_error}")
                    time.sleep(5)
                    continue
                    
        except Exception as outer_error:
            restart_count += 1
            log_message(f"❌ Outer loop error (restart #{restart_count}): {outer_error}")
            time.sleep(10)
            continue

if __name__ == "__main__":
    main()
