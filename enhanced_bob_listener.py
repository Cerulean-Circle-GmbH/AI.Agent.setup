def process_message(message):
    """Process a single message from Alice"""
    global last_message_time
    
    message_id = f"{message['sender']}_{message['content'][:20]}_{message.get('timestamp', '')}"
    
    if message_id in processed_messages:
        return False  # Already processed
    
    processed_messages.add(message_id)
    last_message_time = time.time()
    
    content = message.get('content', '')
    sender = message.get('sender', '')
    
    if sender != ALICE_NAME:
        return False
    
    log_message(f"📨 Received from Alice: {content[:100]}...")
    
    # Execute tasks first
    task_results = execute_task(content)
    
    # Generate response based on message type
    if "orchestration" in content.lower() or "flow" in content.lower():
        response = "✅ ORCHESTRATION UNDERSTOOD! I understand the communication flow: 1) QA User → Alice → Bob (task execution), 2) Bob → Alice (results), 3) Alice → QA User (summary). I will: 1) Confirm completion after each task, 2) Wait for next task, 3) NOT expect immediate response from you. I am ready for the next task cycle!"
    
    elif "task" in content.lower() or "create" in content.lower() or "generate" in content.lower():
        if task_results:
            response = f"✅ TASK COMPLETED! {' '.join(task_results)}. I am ready for your next task!"
        else:
            response = f"I understand your task request: '{content[:50]}...'. I will process this immediately and respond with results."
    
    elif "ping" in content.lower():
        response = "pong - Bob is listening and ready!"
    
    elif "hello" in content.lower() or "hi" in content.lower():
        response = f"Hello Alice! I am Bob in enhanced automatic listening mode. I received your message: '{content}'. How can I help you today?"
    
    else:
        # Generic response for other messages
        response = f"I received your message: '{content}'. I am in enhanced automatic listening mode and ready to help with any tasks you need."
    
    # Send response
    send_message(response)
    
    # Send summary if tasks were executed
    if task_results:
        summary = f"📋 TASK SUMMARY: {' '.join(task_results)}. All tasks completed successfully. Ready for next message."
        send_message(summary)
    
    return True

def check_health():
    """Check if services are healthy"""
    try:
        gateway_health = requests.get(f"{GATEWAY_URL}/health", timeout=5)
        bob_health = requests.get(f"{BOB_ENDPOINT}/health", timeout=5)
        return gateway_health.status_code == 200 and bob_health.status_code == 200
    except:
        return False

def main():
    """Main listening loop with auto-restart capability"""
    global restart_count
    
    log_message("🤖 Enhanced Bob's Automatic Listening Mode Started")
    log_message(f"📡 Monitoring Gateway: {GATEWAY_URL}")
    log_message(f"📤 Sending through: {BOB_ENDPOINT}")
    log_message("🔄 Entering continuous listening loop with auto-restart...")
    log_message("⏹️  Press Ctrl+C to stop")
    
    try:
        while True:
            # Check health periodically
            if not check_health():
                log_message("⚠️  Health check failed, waiting for services to recover...")
                time.sleep(5)
                continue
            
            # Get messages
            messages = get_messages()
            
            # Process new messages
            new_messages_processed = 0
            for message in messages:
                if process_message(message):
                    new_messages_processed += 1
            
            if new_messages_processed > 0:
                log_message(f"✅ Processed {new_messages_processed} new message(s)")
                restart_count = 0  # Reset restart count on successful processing
            
            # Check if we need to restart (no messages for 30 seconds)
            if time.time() - last_message_time > 30 and restart_count < MAX_RESTART_COUNT:
                restart_count += 1
                log_message(f"🔄 No messages for 30 seconds, restarting listener (attempt {restart_count}/{MAX_RESTART_COUNT})")
                time.sleep(2)
                continue
            
            # Wait before next check
            time.sleep(2)  # Check every 2 seconds
            
    except KeyboardInterrupt:
        log_message("🛑 Enhanced automatic listening mode stopped by user")
        sys.exit(0)
    except Exception as e:
        log_message(f"❌ Error in listening loop: {e}")
        if restart_count < MAX_RESTART_COUNT:
            restart_count += 1
            log_message(f"🔄 Restarting due to error (attempt {restart_count}/{MAX_RESTART_COUNT})")
            time.sleep(5)
            main()  # Recursive restart
        else:
            log_message("❌ Max restart attempts reached, exiting")
            sys.exit(1)

if __name__ == "__main__":
    main()
